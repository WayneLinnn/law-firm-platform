# -*- coding: utf-8 -*-
"""风险代理的合法性规则。

★ 这是整个 billing 模块里唯一**不由律所说了算**的部分。

  费率多少、打几折、分几期，都是律所的生意，系统不该有意见。
  但「哪些案子不许风险代理」「风险代理最高收多少」是**规章定的**
  （《律师服务收费管理办法》，发改价格〔2006〕611 号）：

      第十一条  四类民事案件不得实行风险代理收费
      第十二条  刑事、行政、国家赔偿、群体性诉讼案件禁止风险代理
      第十三条  风险代理最高收费不得高于合同约定标的额的 30%

  违规收费的后果不是"账算错了"，是司法行政机关的处罚、退费，
  以及执业记录上留下一笔。所以这一层是**硬拦**，不是提示。

★ 但硬拦有个前提：系统得真的知道这案子属于哪一类。

  「刑事」「行政」这两类，看案由就能定 —— 整类禁止，硬拦。
  「劳动争议」不行：禁的是"请求支付劳动报酬"，而竞业限制赔偿、
  违法解除赔偿金这些同样挂在劳动争议下面，并不当然禁止。
  系统看不到具体诉请，**这种情况下装作知道比不知道更危险**。
  所以劳动、人身损害这类是 `confirm`：明确写出禁区在哪，
  让律师自己判断并**签字确认**，确认记录落库。

  三种档位：
      block    整类禁止 —— 直接拒绝，说清依据
      confirm  部分禁止 —— 写清禁区，律师确认后放行，确认留痕
      allow    没有已知限制 —— 但 30% 上限照样管

★ 和 task 的时限规则一样：**每条都写清依据，每条都说清自己盖不住什么。**
  这张表也是数据 —— 律所可以加自己的口径（比如某些所自律更严），
  但**不能把 block 改成 allow**：那是规章，不是所里的规矩。
"""
from __future__ import annotations

from decimal import Decimal

#: 风险代理收费上限。**法定 30%**，不是本所政策，所以是常量不是配置项。
#:
#: ★ 基数是「合同约定标的额」，**不含代垫费用** ——
#:   把诉讼费、鉴定费混进基数算，上限就放宽了，而放宽的方向永远是超收。
CONTINGENCY_MAX_RATE = Decimal("0.30")

#: 依据条文。报错时要原样给出来 —— 一句"不允许"律师不会信，
#: 也没法拿去跟客户解释为什么不能这么签。
BASIS_ARTICLE_11 = "《律师服务收费管理办法》第十一条"
BASIS_ARTICLE_12 = "《律师服务收费管理办法》第十二条"
BASIS_ARTICLE_13 = "《律师服务收费管理办法》第十三条"


#: (案由 code, 档位, 依据, 说明, 盖不住什么)
#:
#: 案由 code 对应 case 模块的案由字典；`category` 前缀 `cat:` 表示
#: 匹配整个大类（civil / criminal / admin / nonlit）。
CONTINGENCY_RULES = (
    # ---------------- 整类禁止（第十二条）----------------
    {
        "match": "cat:criminal",
        "level": "block",
        "basis": BASIS_ARTICLE_12,
        "reason": "刑事诉讼案件**禁止**风险代理收费。",
        "caveat": "包括侦查、审查起诉、审判各阶段。刑事案件的非诉法律服务"
                  "（如合规咨询）不在此列，但那应当另建非诉案件，不要挂在刑事案由下。",
    },
    {
        "match": "cat:admin",
        "level": "block",
        "basis": BASIS_ARTICLE_12,
        "reason": "行政诉讼案件**禁止**风险代理收费。",
        "caveat": "行政复议、行政机关内部的申诉程序是否一体适用，各地口径不一，"
                  "本条只覆盖行政诉讼。国家赔偿案件同样禁止，若本所另设了"
                  "国家赔偿案由，请自行加一条规则。",
    },

    # ---------------- 部分禁止，要律师确认（第十一条）----------------
    {
        "match": "labor",
        "level": "confirm",
        "basis": BASIS_ARTICLE_11,
        "reason": "劳动争议中，**请求支付劳动报酬**的不得风险代理；"
                  "请求给予社会保险待遇、工伤赔偿的同样不得。",
        "caveat": "禁的是**诉讼请求**不是案由 —— 竞业限制补偿、违法解除赔偿金"
                  "这类请求并不当然禁止。系统看不到你的具体诉请，"
                  "**只能由你判断**：诉请里只要含劳动报酬、社保待遇、工伤赔偿，"
                  "这部分就不能按风险收费。",
    },
    {
        "match": "cat:civil",
        "level": "confirm",
        "basis": BASIS_ARTICLE_11,
        "reason": "以下四类民事请求不得风险代理：①婚姻、继承；"
                  "②社会保险待遇或最低生活保障；③赡养费、扶养费、抚育费、"
                  "抚恤金、救济金、工伤赔偿金；④劳动报酬。",
        "caveat": "本条按**大类**提示，覆盖不到具体诉请。一个买卖合同纠纷里"
                  "如果夹着追索劳动报酬的请求，系统一样看不出来。"
                  "签之前请对着诉请逐条过一遍。",
    },
)


def rule_for(cause_code: str, cause_category: str) -> dict:
    """给一个案由，找出适用的风险代理规则。

    ★ 精确案由优先于大类：劳动争议属于民事，但它有自己更具体的一条。
      找不到就返回 allow —— **但 30% 上限照样管**，那条不看案由。
    """
    by_code = {r["match"]: r for r in CONTINGENCY_RULES}
    if cause_code and cause_code in by_code:
        return by_code[cause_code]
    cat_key = "cat:" + (cause_category or "")
    if cat_key in by_code:
        return by_code[cat_key]
    return {
        "match": "", "level": "allow", "basis": "",
        "reason": "",
        "caveat": "未匹配到已知禁区，**不等于一定可以**：禁止的是具体诉讼请求，"
                  "系统只看得到案由。签之前请对着诉请自行核对"
                  "《律师服务收费管理办法》第十一条、第十二条。",
    }
